"""Expose the flask-diffsynth image-edit contract and proxy it to vLLM-Omni.

Public request fields (multipart/form-data):
  image: required source image
  prompt: required edit instruction
  mask: optional mask image
  mask_mode: mask_image (latent blending) or reference (second RGB reference).
             Overrides --mask-mode; reference requires mask.
  seed: optional integer seed forwarded to the upstream engine
  lora: optional JSON object {"name": "...", "path": "...", "scale": 1.0}
        Overrides the CLI default adapter; scale=0 disables it for this request.

By default the upstream request renames ``mask`` to ``mask_image``. Reference
mode sends ordered repeated ``image`` parts: source, then RGB mask, without
``mask_image``. It does not paste known pixels back into the output. Initial
diffusion noise is generated by the upstream engine; this adapter never sends
an external target/noise image or ``reference_image``.
"""

